// Turns openapi.json (dumped from the Python API) into src/lib/api-schema.d.ts.
//
//   npm run gen:types          write the file
//   npm run check:api-types    fail if the committed file is out of date (also run by the test suite)
//
// To refresh openapi.json itself after changing the API:  python ../api/scripts/dump_openapi.py
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

export const SCHEMA = here("../openapi.json");
export const TARGET = here("../src/lib/api-schema.d.ts");

const BANNER = `/* eslint-disable */
// Generated by scripts/gen-api-types.mjs from openapi.json. Do not edit by hand.
// Refresh: python ../api/scripts/dump_openapi.py && npm run gen:types

`;

export async function generate() {
  const spec = JSON.parse(readFileSync(SCHEMA, "utf8"));
  const ast = await openapiTS(spec);
  return BANNER + astToString(ast);
}

const normalize = (text) => text.replace(/\r\n/g, "\n");

async function main() {
  const wanted = await generate();
  if (process.argv.includes("--check")) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (normalize(current) !== normalize(wanted)) {
      console.error("src/lib/api-schema.d.ts is out of date. Run: npm run gen:types");
      process.exit(1);
    }
    console.log("api-schema.d.ts is up to date.");
    return;
  }
  writeFileSync(TARGET, wanted, "utf8");
  console.log("Wrote src/lib/api-schema.d.ts");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
